import { useMemo } from "react";
import { Loading, Page, Section, Tag, useRangeArgs } from "../components/ui";
import { useFilters, useRpc, useTable } from "../state";
import { buildInsights, type Insight } from "../lib/insights";
import { sum } from "../lib/metrics";

export function useInsights() {
  const f = useFilters();
  const { range, cmp, prevRange } = useRangeArgs();
  const queries = useRpc<any[]>("rpc_gsc_queries", { ...cmp, p_limit: 500 });
  const landing = useRpc<any[]>("rpc_ga4_landing", cmp);
  const camps = useRpc<any[]>("rpc_ads_campaigns", range);
  const prevCamps = useRpc<any[]>("rpc_ads_campaigns", prevRange);
  const days = useRpc<any[]>("rpc_daily_series", range);
  const prevDays = useRpc<any[]>("rpc_daily_series", prevRange);
  const attr = useRpc<any[]>("rpc_attribution", range);
  const funnel = useRpc<Record<string, number>>("rpc_funnel", range);
  const acq = useRpc<any[]>("rpc_ga4_acquisition", range);
  const integ = useTable<any>("integrations", (q) => q.select("source,label,status,last_success_at,last_error"));

  const loading = [queries, landing, camps, days, attr, funnel, integ].some((s) => s.loading);
  const items = useMemo<Insight[] | null>(() => {
    if (loading) return null;
    const num = (v: any) => (v == null ? null : Number(v));
    return buildInsights({
      periodLabel: f.label, compareLabel: f.prevLabel,
      queries: (queries.data ?? []).map((q) => ({ ...q, clicks: +q.clicks, impressions: +q.impressions, avg_position: num(q.avg_position), prev_clicks: num(q.prev_clicks), prev_impressions: num(q.prev_impressions) })),
      landing: f.prev ? (landing.data ?? []).map((l) => ({ ...l, sessions: +l.sessions, prev_sessions: num(l.prev_sessions), key_events: num(l.key_events) })) : [],
      campaigns: (camps.data ?? []).map((c) => ({ ...c, cost: +c.cost, conversions: +c.conversions, clicks: +c.clicks })),
      prevCampaigns: f.prev ? (prevCamps.data ?? []).map((c) => ({ ...c, cost: +c.cost, conversions: +c.conversions, clicks: +c.clicks })) : [],
      days: (days.data ?? []).map((d) => ({ date: d.date, ga4_sessions: num(d.ga4_sessions), ads_cost: num(d.ads_cost), leads: num(d.leads), gsc_clicks: num(d.gsc_clicks) })),
      prevDays: f.prev ? (prevDays.data ?? []).map((d) => ({ date: d.date, ga4_sessions: num(d.ga4_sessions), ads_cost: num(d.ads_cost), leads: num(d.leads), gsc_clicks: num(d.gsc_clicks) })) : [],
      integrations: integ.data ?? [],
      attribution: (attr.data ?? []).map((a) => ({ ...a, leads: +a.leads, booked: +a.booked, spend: num(a.spend) })),
      funnel: funnel.data ? Object.fromEntries(Object.entries(funnel.data).map(([k, v]) => [k, Number(v)])) : null,
      ga4KeyEventsTotal: acq.data && acq.data.length ? sum(acq.data, (r) => Number(r.key_events)) : null,
    });
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading, queries.data, landing.data, camps.data, prevCamps.data, days.data, prevDays.data, attr.data, funnel.data, acq.data, integ.data]);
  return { items, loading };
}

const tone = { high: "bad", medium: "warn", low: "neutral", info: "info" } as const;

export function InsightList({ items }: { items: Insight[] | null }) {
  if (!items) return <Loading />;
  if (!items.length) return <div className="empty">Nothing flagged for this period.</div>;
  return (
    <div className="insights">
      {items.map((i) => (
        <article key={i.id} className={`insight sev-${i.severity}`}>
          <div className="insight-top"><Tag tone={tone[i.severity]}>{i.severity}</Tag><span className="muted">{i.area}</span></div>
          <h3>{i.title}</h3>
          <dl>
            <dt>Evidence</dt><dd>{i.evidence}</dd>
            <dt>Period</dt><dd>{i.comparison}</dd>
            <dt>Opportunity</dt><dd>{i.opportunity}</dd>
            <dt>Suggested action</dt><dd>{i.action}</dd>
          </dl>
          {i.link && <a className="btn ghost" href={`#${i.link}`}>Open →</a>}
        </article>
      ))}
    </div>
  );
}

export default function Insights() {
  const { items } = useInsights();
  return (
    <Page eyebrow="Analysis" title="Insights & recommendations"
      intro={<>Generated by fixed rules from the data on this dashboard, not by a language model. They point at correlations worth checking — they don't prove cause. <Tag tone="info">Automated interpretation</Tag></>}>
      <Section title={`${items?.length ?? "…"} findings`}><InsightList items={items} /></Section>
    </Page>
  );
}
